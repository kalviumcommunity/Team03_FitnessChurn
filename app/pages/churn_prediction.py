import streamlit as st
import pandas as pd
from pathlib import Path


# --------------------------------------------------
# LOAD PREDICTION DATA
# --------------------------------------------------

PREDICTION_PATH = (
    Path(__file__).resolve().parent.parent.parent
    / "data"
    / "processed"
    / "churn_predictions.csv"
)

predictions_df = pd.read_csv(PREDICTION_PATH)


# --------------------------------------------------
# PAGE CONFIGURATION
# --------------------------------------------------

st.set_page_config(
    page_title="Churn Prediction",
    page_icon="⚡",
    layout="wide"
)


# --------------------------------------------------
# PAGE HEADER
# --------------------------------------------------

st.title("Churn Risk Prediction")

st.caption(
    "Identify members who are most likely to churn based on behavioural patterns."
)

st.divider()


# --------------------------------------------------
# CALCULATE RISK COUNTS
# --------------------------------------------------

total_members = len(predictions_df)

high_risk = (
    predictions_df["risk_status"] == "High"
).sum()

medium_risk = (
    predictions_df["risk_status"] == "Medium"
).sum()

low_risk = (
    predictions_df["risk_status"] == "Low"
).sum()


# --------------------------------------------------
# KPI CARDS
# --------------------------------------------------

col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric(
        "Members Analysed",
        f"{total_members:,}"
    )

with col2:
    st.metric(
        "High Risk",
        f"{high_risk:,}"
    )

with col3:
    st.metric(
        "Medium Risk",
        f"{medium_risk:,}"
    )

with col4:
    st.metric(
        "Low Risk",
        f"{low_risk:,}"
    )


st.divider()


# --------------------------------------------------
# PREDICTION TABLE
# --------------------------------------------------

st.subheader("Predictive Churn Register")

st.caption(
    "Churn probability and risk levels generated by the machine learning model."
)


# Create a copy so the original prediction data is not changed
prediction_display = predictions_df[
    [
        "Contract_period",
        "Avg_class_frequency_current_month",
        "Lifetime",
        "engagement_level",
        "churn_probability",
        "risk_status"
    ]
].copy()


# Convert probability from decimal to percentage
prediction_display["churn_probability"] = (
    prediction_display["churn_probability"] * 100
).round(1).astype(str) + "%"


# Rename columns for the UI
prediction_display = prediction_display.rename(
    columns={
        "Contract_period": "Contract Period",
        "Avg_class_frequency_current_month":
            "Current Month Frequency",
        "Lifetime":
            "Lifetime",
        "engagement_level":
            "Engagement Level",
        "churn_probability":
            "Churn Probability",
        "risk_status":
            "Risk Status"
    }
)


# Display prediction table
st.dataframe(
    prediction_display,
    use_container_width=True,
    hide_index=True
)


st.divider()


# --------------------------------------------------
# RISK DISTRIBUTION
# --------------------------------------------------

st.subheader("Risk Distribution")

risk_data = pd.DataFrame(
    {
        "Risk Level": [
            "High",
            "Medium",
            "Low"
        ],
        "Members": [
            high_risk,
            medium_risk,
            low_risk
        ]
    }
)

st.bar_chart(
    risk_data,
    x="Risk Level",
    y="Members"
)


st.divider()


# --------------------------------------------------
# MODEL INFORMATION
# --------------------------------------------------

st.subheader("Prediction Overview")

st.info(
    "The churn probabilities and risk classifications shown above "
    "are generated by the machine learning model developed from "
    "the cleaned customer dataset."
)


# --------------------------------------------------
# ACTIONS
# --------------------------------------------------

col1, col2 = st.columns(2)

with col1:

    csv_data = predictions_df.to_csv(index=False)

    st.download_button(
        label="Export Prediction CSV",
        data=csv_data,
        file_name="churn_predictions.csv",
        mime="text/csv"
    )


with col2:

    if st.button("Refresh Predictions"):

        st.cache_data.clear()

        st.rerun()


# --------------------------------------------------
# FOOTER
# --------------------------------------------------

st.divider()

st.caption(
    "Fitness Retain AI • Churn Prediction"
)